const TABLES = { en: EN, pt: PT };

/**
 * @param {"en" | "pt"} lang
 * @param {string} key
 * @param {Record<string, string | number>} [values]
 * @returns {string}
 * @example gameText("pt", "battleRound", { round: 2 }) // "Rodada 2"
 */
export function gameText(lang, key, values = {}) {
  const template = TABLES[lang]?.[key] ?? EN[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name) => String(values[name] ?? match));
}

/**
 * Translate a combat log line ("heroAttack|12|7|5|1") into prose.
 * @param {"en" | "pt"} lang
 * @param {string} line
 * @param {number} [wonXp]
 * @returns {string}
 */
export function battleLogText(lang, line, wonXp = 0) {
  const [kind, ...parts] = line.split("|");
  const key = `log${kind.charAt(0).toUpperCase()}${kind.slice(1)}`;
  const crit = Number(parts[3]) > 0 ? gameText(lang, "logCrit", { 0: parts[3] }) : "";
  const values = { 0: parts[0] ?? "", 1: parts[1] ?? "", 2: parts[2] ?? "", crit };
  if (kind === "won") values[0] = String(wonXp);
  return gameText(lang, key, values);
}

/**
 * Static nodes: data-game-i18n="key".
 * @param {ParentNode} root
 * @param {"en" | "pt"} lang
 */
export function applyGameTranslations(root, lang) {
  for (const node of root.querySelectorAll("[data-game-i18n]"))
    node.textContent = gameText(lang, node.getAttribute("data-game-i18n") ?? "");
}
